using System.Text;
using System.Text.Json;
using Yrk.PdfStudio.App.Services;

namespace Yrk.PdfStudio.Core.Tests;

public sealed class ErrorCodeDocTests
{
    private static string RepositoryRoot
    {
        get
        {
            for (var folder = new DirectoryInfo(AppContext.BaseDirectory); folder is not null; folder = folder.Parent)
                if (Directory.Exists(Path.Combine(folder.FullName, "src", "Yrk.PdfStudio.App"))) return folder.FullName;
            throw new DirectoryNotFoundException("Cannot locate repository root for error code documentation.");
        }
    }

    [Fact]
    public void Error_code_documentation_matches_the_catalog()
    {
        var root = RepositoryRoot;
        var path = Path.Combine(root, "docs", "error-codes.md");
        var expected = BuildDocument(Path.Combine(root, "src", "Yrk.PdfStudio.App", "Localization", "th.json")).Replace("\r\n", "\n", StringComparison.Ordinal);

        if (Environment.GetEnvironmentVariable("YRK_REGEN_DOCS") == "1")
        {
            Directory.CreateDirectory(Path.GetDirectoryName(path)!);
            File.WriteAllText(path, expected, new UTF8Encoding(false));
            return;
        }

        Assert.True(File.Exists(path)
            && string.Equals(File.ReadAllText(path).Replace("\r\n", "\n", StringComparison.Ordinal), expected, StringComparison.Ordinal),
            "Error-code documentation is missing or out of date. Run YRK_REGEN_DOCS=1 dotnet test --filter ErrorCodeDoc");
    }

    private static string BuildDocument(string thaiPath)
    {
        using var translations = JsonDocument.Parse(File.ReadAllText(thaiPath), new JsonDocumentOptions
        {
            CommentHandling = JsonCommentHandling.Skip,
            AllowTrailingCommas = true,
        });

        var builder = new StringBuilder();
        builder.AppendLine("# รหัสข้อผิดพลาด | Error codes");
        builder.AppendLine();
        builder.AppendLine("เอกสารนี้สร้างโดย `ErrorCodeDocTests` จากแคตตาล็อกข้อผิดพลาด | This file is generated by `ErrorCodeDocTests` from the error catalog.");
        builder.AppendLine();

        foreach (var area in ErrorCatalog.All.GroupBy(error => error.Code.Split('-')[1], StringComparer.Ordinal))
        {
            builder.Append("## ").AppendLine(area.Key);
            builder.AppendLine();
            builder.AppendLine("| รหัส | ข้อความ (ไทย) | Message (English) | สิ่งที่ทำได้ / What you can do |");
            builder.AppendLine("| --- | --- | --- | --- |");
            foreach (var error in area)
            {
                var messageThai = Translation(translations.RootElement, error.Message);
                var nextStepThai = Translation(translations.RootElement, error.NextStep);
                builder.Append("| ").Append(Escape(error.Code)).Append(" | ").Append(Escape(messageThai)).Append(" | ")
                    .Append(Escape(error.Message)).Append(" | ").Append(Escape(nextStepThai)).Append("<br>")
                    .Append(Escape(error.NextStep)).AppendLine(" |");
            }
            builder.AppendLine();
        }

        return builder.ToString();
    }

    private static string Translation(JsonElement root, string key)
    {
        Assert.True(root.TryGetProperty(key, out var value) && value.ValueKind == JsonValueKind.String,
            $"Missing Thai translation: {key}");
        return value.GetString()!;
    }

    private static string Escape(string value) => value.Replace("|", "\\|", StringComparison.Ordinal)
        .Replace("\r\n", "<br>", StringComparison.Ordinal)
        .Replace("\n", "<br>", StringComparison.Ordinal)
        .Replace("\r", "<br>", StringComparison.Ordinal);
}
