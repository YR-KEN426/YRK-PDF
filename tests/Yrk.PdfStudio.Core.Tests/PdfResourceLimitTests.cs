    private static void AssertFast(Stopwatch timer) =>
        Assert.True(timer.Elapsed < TimeSpan.FromSeconds(5), $"Operation took {timer.Elapsed}.");

    [Theory]
    [InlineData("Prev", 4294967295L)]
    [InlineData("Prev", -1L)]
    [InlineData("XRefStm", 4294967295L)]
    [InlineData("XRefStm", -1L)]
    [InlineData("startxref", 4294967295L)]
    [InlineData("startxref", -1L)]
    public void Out_of_bounds_xref_offsets_repair_without_crashing(string key, long offset)
    {
        var bytes = Pdf();
        var text = Encoding.ASCII.GetString(bytes);
        text = key == "startxref"
            ? text[..text.LastIndexOf("startxref", StringComparison.Ordinal)] + $"startxref\n{offset}\n%%EOF\n"
            : text.Replace("/Root 1 0 R >>", $"/Root 1 0 R /{key} {offset} >>", StringComparison.Ordinal);
        var timer = Stopwatch.StartNew();
        var document = CosDocument.Load(Encoding.ASCII.GetBytes(text));
        Assert.True(document.WasReconstructed);
        Assert.Single(document.GetPages());
        AssertFast(timer);
    }

    [Theory]
    [InlineData("0 0 0", "")]
    [InlineData("1 9 0", "")]
    [InlineData("1 +4294967297 0", "")]
    [InlineData("1 0 0", "")]
    [InlineData("1 0 0", "/Index [0 1000000000]")]
    [InlineData("1 0 0", "/Index [0 1 1 1000000000]")]
    public void Invalid_xref_stream_widths_and_counts_repair_quickly(string widths, string index)
    {
        var source = Pdf();
        var xref = (int)CosDocument.Load(source).StartXref;
        var bytes = source[..xref].Concat(Encoding.ASCII.GetBytes(
            $"5 0 obj\n<< /Type /XRef /Root 1 0 R /W [{widths}] /Size 1000000000 {index} /Length 1 >>\nstream\n\0\nendstream\nendobj\nstartxref\n{xref}\n%%EOF\n")).ToArray();
        var allocated = GC.GetAllocatedBytesForCurrentThread();
        var timer = Stopwatch.StartNew();
        var document = CosDocument.Load(bytes);
        Assert.True(document.WasReconstructed);
        Assert.Single(document.GetPages());
        AssertFast(timer);
        Assert.True(GC.GetAllocatedBytesForCurrentThread() - allocated < 1024 * 1024);
    }

    [Theory]
    [InlineData(false)]
    [InlineData(true)]
    public void Short_xref_stream_keeps_its_real_xref_without_reconstruction(bool useIndex)
    {
        var source = Pdf();
        var original = CosDocument.Load(source);
        using var output = new MemoryStream();
        output.Write(source.AsSpan(0, (int)original.StartXref));
        var writer = new CosWriter(output);
        var xref = writer.Position;
        var entries = new List<byte>();
        for (var number = 0; number <= 5; number++)
        {
            var generation = number == 4 ? 7 : 0;
            var offset = number == 0 ? 0 : number == 5 ? (int)xref
                : source.AsSpan().IndexOf(Encoding.ASCII.GetBytes($"{number} {generation} obj\n"));
            entries.Add(number == 0 ? (byte)0 : (byte)1);
            entries.AddRange([(byte)(offset >> 24), (byte)(offset >> 16), (byte)(offset >> 8), (byte)offset]);
            entries.AddRange(number == 0 ? new byte[] { 255, 255 } : new byte[] { 0, (byte)generation });
        }
        var header = new CosDictionary().Set("Type", new CosName("XRef"))
            .Set("Root", original.Trailer["Root"]!).Set("W", CosArray.FromNumbers(1, 4, 2))
            .Set("Size", new CosInteger(1000000000));
        if (useIndex) header.Set("Index", CosArray.FromNumbers(0, 3, 3, 999999997));
        writer.WriteIndirectObject(new CosObjectId(5, 0), new CosStream(header, entries.ToArray()));
        writer.WriteRaw($"\nstartxref\n{xref}\n%%EOF\n");

        var timer = Stopwatch.StartNew();
        var document = CosDocument.Load(output.ToArray());
        Assert.False(document.WasReconstructed);
        Assert.True(document.UsesXrefStream);
        Assert.Single(document.GetPages());
        Assert.Equal(42, Assert.IsType<CosInteger>(document.GetObject(new CosObjectId(4, 7))).Value);
        AssertFast(timer);
    }

    private static CosStream LzwStream(byte[] data, int earlyChange) => new(
        new CosDictionary().Set("Filter", new CosName("LZWDecode"))
            .Set("DecodeParms", new CosDictionary().Set("EarlyChange", new CosInteger(earlyChange))), data);

    // Pack codes with PDF's MSB-first bit order and decoder-side width transitions.
    private static byte[] PackLzw(IEnumerable<int> codes, int earlyChange)
    {
        var bytes = new List<byte>();
        int width = 9, tableCount = 258, pending = 0, bits = 0;
        var previous = false;
        foreach (var code in codes)
        {
            for (var bit = width - 1; bit >= 0; bit--)
            {
                pending = (pending << 1) | ((code >> bit) & 1);
                if (++bits == 8)
                {
                    bytes.Add((byte)pending);
                    bits = pending = 0;
                }
            }

            if (code == 256)
            {
                width = 9;
                tableCount = 258;
                previous = false;
            }
            else if (code != 257)
            {
                if (previous && tableCount < 4096) tableCount++;
                previous = true;
                if (width < 12 && tableCount >= (1 << width) - earlyChange) width++;
            }
        }

        if (bits > 0) bytes.Add((byte)(pending << (8 - bits)));
        return bytes.ToArray();
    }

    private static byte[] Pdf(params (CosObjectId Id, CosObject Value)[] extra)
    {
        using var output = new MemoryStream();
        var writer = new CosWriter(output);
        writer.WriteRaw("%PDF-1.7\n");
        (CosObjectId Id, CosObject Value)[] basic =
        [
            (new(1, 0), new CosDictionary().Set("Type", new CosName("Catalog")).Set("Pages", new CosReference(2, 0))),
            (new(2, 0), new CosDictionary().Set("Type", new CosName("Pages")).Set("Count", new CosInteger(1))
                .Set("Kids", new CosArray([new CosReference(3, 0)]))),
            (new(3, 0), new CosDictionary().Set("Type", new CosName("Page")).Set("Parent", new CosReference(2, 0))
                .Set("MediaBox", new CosArray([new CosInteger(0), new CosInteger(0), new CosInteger(100), new CosInteger(100)]))),
            (new(4, 7), new CosInteger(42)),
        ];
        var entries = new List<(CosObjectId Id, long Offset)>();
        foreach (var (id, value) in basic.Concat(extra))
        {
            entries.Add((id, writer.Position));
            writer.WriteIndirectObject(id, value);
        }

        var xref = writer.Position;
        writer.WriteRaw("xref\n0 1\n0000000000 65535 f\r\n");
        foreach (var (id, offset) in entries)
        {
            writer.WriteRaw($"{id.Number} 1\n{offset:D10} {id.Generation:D5} n\r\n");
        }

        writer.WriteRaw($"trailer\n<< /Size 2147483647 /Root 1 0 R >>\nstartxref\n{xref}\n%%EOF\n");
        return output.ToArray();
    }
