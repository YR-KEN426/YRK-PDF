    [Fact]
    public void Lzw_bomb_throws_at_the_production_limit()
    {
        // Grow a run of 'A' to the last dictionary slot, then keep using it with a full table.
        var codes = new List<int> { 256, 65 };
        codes.AddRange(Enumerable.Range(258, 4096 - 258));
        codes.AddRange(Enumerable.Repeat(4095, 71000));
        codes.Add(257);
        var stream = LzwStream(PackLzw(codes, 1), 1);

        Assert.Throws<PdfException>(() => CosFilters.Decode(stream, x => x));
    }

    [Theory]
    [InlineData(0)]
    [InlineData(1)]
    public void Lzw_keeps_a_full_table_until_clear_and_resets_code_width(int earlyChange)
    {
        var codes = new List<int> { 256, 65 };
        codes.AddRange(Enumerable.Range(258, 4096 - 258));
        codes.AddRange(Enumerable.Repeat(4095, 10));
        codes.AddRange([256, 66, 258, 257]);
        var decoded = CosFilters.Decode(LzwStream(PackLzw(codes, earlyChange), earlyChange), x => x);
        const int longest = 3839;
        Assert.Equal((longest * (longest + 1) / 2) + (10 * longest) + 3, decoded.Length);
        Assert.All(decoded.Take(decoded.Length - 3), b => Assert.Equal((byte)'A', b));
        Assert.Equal("BBB", Encoding.ASCII.GetString(decoded[^3..]));
    }

    [Fact]
    public void Lzw_checks_the_special_entry_before_allocating_or_appending()
    {
        var stream = LzwStream(PackLzw([256, 65, 258, 259, 257], 1), 1);
        Assert.Equal("AAAAAA", Encoding.ASCII.GetString(CosFilters.Decode(stream, x => x, 6)));
        Assert.Throws<PdfException>(() => CosFilters.Decode(stream, x => x, 5));
    }

    [Fact]
    public void Lzw_checks_an_existing_entry_before_appending()
    {
        var stream = LzwStream(PackLzw([256, 65, 65, 65, 257], 1), 1);
        Assert.Equal("AAA", Encoding.ASCII.GetString(CosFilters.Decode(stream, x => x, 3)));
        Assert.Throws<PdfException>(() => CosFilters.Decode(stream, x => x, 2));
    }

    [Fact]
    public async Task Huge_trailer_size_opens_normally_in_under_five_seconds()
    {
        var bytes = Pdf();
        var folder = Directory.CreateTempSubdirectory("yrk-resource-tests-");
        try
        {
            var path = Path.Combine(folder.FullName, "generated.pdf");
            File.WriteAllBytes(path, bytes);
            using var engine = new PdfiumEngine();
            var timer = Stopwatch.StartNew();
            await using var document = await engine.OpenAsync(path).WaitAsync(TimeSpan.FromSeconds(5));
            Assert.Equal(1, document.PageCount);
            AssertFast(timer);
        }
        finally
        {
            folder.Delete(true);
        }
    }

    [Fact]
    public void Huge_trailer_size_loads_and_repairs_in_under_five_seconds()
    {
        var bytes = Pdf();
        var timer = Stopwatch.StartNew();
        var document = CosDocument.Load(bytes);
        Assert.False(document.WasReconstructed);
        Assert.Single(document.GetPages());
        AssertFast(timer);

        using var input = new MemoryStream(bytes);
        timer.Restart();
        Assert.Null(ToUnicodeRepair.Build(input));
        AssertFast(timer);
        Assert.Contains(new CosObjectId(4, 7), document.ObjectIds);
        Assert.DoesNotContain(new CosObjectId(0, 65535), document.ObjectIds);
    }

    [Fact]
    public void Huge_trailer_size_trims_quickly_and_preserves_nonzero_generations()
    {
        var bytes = Pdf();
        var update = new CosIncrementalUpdate(CosDocument.Load(bytes));
        update.Replace(new CosObjectId(4, 7), new CosInteger(99));
        var saved = update.Build().Bytes.Concat(Enumerable.Repeat((byte)' ', 1024)).ToArray();
        var timer = Stopwatch.StartNew();
        var trimmed = CosUpdateTrimmer.Trim(bytes, saved);
        AssertFast(timer);
        Assert.True(trimmed.Length < saved.Length);
        var document = CosDocument.Load(trimmed);
        Assert.False(document.WasReconstructed);
        Assert.Contains(new CosObjectId(4, 7), document.ObjectIds);
        Assert.Equal(99, Assert.IsType<CosInteger>(document.GetObject(new CosObjectId(4, 7))).Value);
    }

    [Fact]
    public void Reconstructed_xref_preserves_nonzero_generations()
    {
        // Hide startxref from the tail scan to exercise recovery using only generated bytes.
        var bytes = Pdf().Concat(Enumerable.Repeat((byte)' ', 2048)).ToArray();
        var document = CosDocument.Load(bytes);
        Assert.True(document.WasReconstructed);
        Assert.Contains(new CosObjectId(4, 7), document.ObjectIds);
        Assert.Equal(42, Assert.IsType<CosInteger>(document.GetObject(new CosObjectId(4, 7))).Value);
    }

    [Fact]
    public void Signature_revision_comparison_handles_huge_size_and_nonzero_generation()
    {
        var bytes = Pdf();
        var original = CosDocument.Load(bytes);
        var update = new CosIncrementalUpdate(original);
        update.Replace(new CosObjectId(1, 0), original.Catalog.Clone().Set("DSS", new CosDictionary()));
        var saved = update.Build().Bytes;
        var method = typeof(PdfSignatureVerifier).GetMethod("OnlyValidationDataAfter", BindingFlags.Static | BindingFlags.NonPublic)!;
        var timer = Stopwatch.StartNew();
        Assert.True((bool)method.Invoke(null, [CosDocument.Load(saved), original])!);
        AssertFast(timer);

        update.Replace(new CosObjectId(4, 7), new CosInteger(100));
        saved = update.Build().Bytes;
        Assert.False((bool)method.Invoke(null, [CosDocument.Load(saved), original])!);
    }

    [Fact]
    public void Cmap_decoding_uses_one_budget_for_all_maps_and_resets_for_each_open()
    {
        var map = new CosStream(new CosDictionary().Set("Filter", new CosName("FlateDecode")),
            CosFilters.Deflate(Encoding.ASCII.GetBytes(new string(' ', 80))));
        var bytes = Pdf(
            (new(10, 7), new CosDictionary().Set("Subtype", new CosName("Type0")).Set("ToUnicode", new CosReference(11, 7))),
            (new(11, 7), map),
            (new(12, 7), new CosDictionary().Set("Subtype", new CosName("Type0")).Set("ToUnicode", new CosReference(13, 7))),
            (new(13, 7), map));

        Assert.Throws<PdfException>(() => ToUnicodeRepair.Build(bytes, 100));
        Assert.Null(ToUnicodeRepair.Build(bytes, 160));
        Assert.Null(ToUnicodeRepair.Build(bytes, 160));
    }

    [Theory]
